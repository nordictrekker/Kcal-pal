-- Kcal-pal initial schema (single-user PWA).
-- Idempotent: safe to re-run from any partial state.
-- Every table uses RLS with policy auth.uid() = user_id.

-- Profile (single row, holds settings + targets)
create table if not exists profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  daily_calorie_target int default 2000,
  daily_protein_target_g int default 130,
  daily_carb_target_g int default 220,
  daily_fat_target_g int default 70,
  daily_fiber_target_g int default 30,
  height_in numeric,
  goal text default 'maintenance',
  created_at timestamptz default now()
);

-- Food log entries
create table if not exists food_entries (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  consumed_at timestamptz not null default now(),
  meal text check (meal in ('breakfast','lunch','dinner','snack')),
  description text not null,
  source text check (source in ('text','photo','barcode')) not null,
  photo_url text,
  barcode text,
  calories numeric,
  protein_g numeric,
  carbs_g numeric,
  fat_g numeric,
  fiber_g numeric,
  serving_size text,
  raw_ai_response jsonb,
  edited_by_user boolean default false,
  created_at timestamptz default now()
);
create index if not exists food_entries_user_consumed_idx
  on food_entries (user_id, consumed_at desc);

-- Body weight (lbs)
create table if not exists body_weights (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  weight_lbs numeric not null,
  measured_at timestamptz not null default now(),
  source text default 'manual'
);
create index if not exists body_weights_user_measured_idx
  on body_weights (user_id, measured_at desc);

-- Oura daily summary
create table if not exists oura_daily (
  user_id uuid not null references auth.users(id) on delete cascade,
  date date not null,
  sleep_score int,
  total_sleep_min int,
  rem_sleep_min int,
  deep_sleep_min int,
  hrv_avg numeric,
  resting_hr int,
  readiness_score int,
  activity_score int,
  steps int,
  temp_deviation numeric,
  raw jsonb,
  primary key (user_id, date)
);

-- Eight Sleep daily summary
create table if not exists eight_sleep_daily (
  user_id uuid not null references auth.users(id) on delete cascade,
  date date not null,
  sleep_score int,
  total_sleep_min int,
  hrv_avg numeric,
  resting_hr int,
  bed_temp_avg_f numeric,
  toss_turns int,
  raw jsonb,
  primary key (user_id, date)
);

-- Cycle tracking (manual entry)
create table if not exists cycle_days (
  user_id uuid not null references auth.users(id) on delete cascade,
  date date not null,
  cycle_day int,
  phase text check (phase in ('menstrual','follicular','ovulatory','luteal')),
  notes text,
  primary key (user_id, date)
);

-- Apple Health imports (one row per quarterly import file)
create table if not exists apple_health_imports (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  imported_at timestamptz default now(),
  date_range_start date,
  date_range_end date,
  records_imported int,
  file_name text
);

-- Apple Health datapoints (long format, one row per metric reading)
create table if not exists apple_health_data (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  metric text not null,
  value numeric not null,
  unit text,
  recorded_at timestamptz not null,
  source text
);
create index if not exists apple_health_data_user_metric_idx
  on apple_health_data (user_id, metric, recorded_at desc);
create unique index if not exists apple_health_data_unique
  on apple_health_data (user_id, metric, recorded_at);

-- Web push subscriptions
create table if not exists push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz default now()
);

