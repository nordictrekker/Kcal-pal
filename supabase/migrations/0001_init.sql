-- Single-user policy: users can only see/touch their own rows.
-- drop-then-create so a partial previous run can't block us.
do $$
declare
  t text;
begin
  for t in
    select unnest(array[
      'profiles', 'food_entries', 'body_weights', 'oura_daily',
      'eight_sleep_daily', 'cycle_days', 'apple_health_imports',
      'apple_health_data', 'push_subscriptions'
    ])
  loop
    execute format('drop policy if exists %I on %I;', t || '_select', t);
    execute format(
      'create policy %I on %I for select using (auth.uid() = user_id);',
      t || '_select', t
    );
    execute format('drop policy if exists %I on %I;', t || '_insert', t);
    execute format(
      'create policy %I on %I for insert with check (auth.uid() = user_id);',
      t || '_insert', t
    );
    execute format('drop policy if exists %I on %I;', t || '_update', t);
    execute format(
      'create policy %I on %I for update using (auth.uid() = user_id) with check (auth.uid() = user_id);',
      t || '_update', t
    );
    execute format('drop policy if exists %I on %I;', t || '_delete', t);
    execute format(
      'create policy %I on %I for delete using (auth.uid() = user_id);',
      t || '_delete', t
    );
  end loop;
end $$;

-- Storage policies for food-photos bucket: owner-only.
drop policy if exists food_photos_select on storage.objects;
create policy food_photos_select
  on storage.objects for select
  using (bucket_id = 'food-photos' and auth.uid() = owner);
drop policy if exists food_photos_insert on storage.objects;
create policy food_photos_insert
  on storage.objects for insert
  with check (bucket_id = 'food-photos' and auth.uid() = owner);
drop policy if exists food_photos_update on storage.objects;
create policy food_photos_update
  on storage.objects for update
  using (bucket_id = 'food-photos' and auth.uid() = owner);
drop policy if exists food_photos_delete on storage.objects;
create policy food_photos_delete
  on storage.objects for delete
  using (bucket_id = 'food-photos' and auth.uid() = owner);

-- Auto-create a profile row on signup.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (user_id) values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Backfill: if you already signed in before the trigger existed, create
-- profile rows for any existing auth users (no-op for new projects).
insert into public.profiles (user_id)
select id from auth.users
on conflict (user_id) do nothing;
